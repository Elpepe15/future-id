-- Future.id schema untuk Supabase
-- Jalankan seluruh file ini di Supabase SQL Editor.
-- Catatan: akun Admin dan Guru BK dibuat oleh pengelola; jangan izinkan user memilih role tersebut saat registrasi publik.

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text not null default '',
  email text,
  nis text,
  role text not null default 'student' check (role in ('student','counselor','admin')),
  created_at timestamptz not null default now()
);

create or replace function public.handle_new_user()
returns trigger language plpgsql security definer set search_path = public
as $$
begin
  insert into public.profiles (id, full_name, email, nis, role)
  values (
    new.id,
    coalesce(new.raw_user_meta_data->>'full_name',''),
    new.email,
    nullif(new.raw_user_meta_data->>'nis',''),
    'student'
  )
  on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert on auth.users
for each row execute procedure public.handle_new_user();

create table if not exists public.career_assessments (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  answers jsonb not null default '{}'::jsonb,
  result_code text,
  result_summary text,
  created_at timestamptz not null default now()
);
create table if not exists public.career_plans (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  goal text not null,
  next_step text not null,
  target_date date,
  status text not null default 'planned',
  created_at timestamptz not null default now()
);
create table if not exists public.consultation_requests (
  id bigint generated by default as identity primary key,
  student_id uuid not null references public.profiles(id) on delete cascade,
  counselor_id uuid references public.profiles(id) on delete set null,
  topic text not null,
  message text not null,
  status text not null default 'pending' check (status in ('pending','scheduled','completed','cancelled')),
  scheduled_at timestamptz,
  private_notes text,
  created_at timestamptz not null default now()
);
create table if not exists public.career_resources (
  id bigint generated by default as identity primary key,
  title text not null,
  category text not null default 'career',
  description text,
  content_url text,
  published boolean not null default false,
  created_by uuid references public.profiles(id) on delete set null,
  created_at timestamptz not null default now()
);
create table if not exists public.career_fields (
  id bigint generated by default as identity primary key,
  title text not null,
  description text,
  skills text[] not null default '{}',
  education_path text,
  created_at timestamptz not null default now()
);

create or replace function public.current_role()
returns text language sql stable security definer set search_path = public
as $$ select role from public.profiles where id = auth.uid() $$;

alter table public.profiles enable row level security;
alter table public.career_assessments enable row level security;
alter table public.career_plans enable row level security;
alter table public.consultation_requests enable row level security;
alter table public.career_resources enable row level security;
alter table public.career_fields enable row level security;

-- Profil: pengguna melihat profil sendiri; BK/Admin dapat melihat profil untuk pendampingan/administrasi.
create policy "profile self read" on public.profiles for select to authenticated using (id = auth.uid() or public.current_role() in ('admin','counselor'));
create policy "profile self update" on public.profiles for update to authenticated using (id = auth.uid()) with check (id = auth.uid() and role = public.current_role());
create policy "profile admin manage" on public.profiles for all to authenticated using (public.current_role() = 'admin') with check (public.current_role() = 'admin');

create policy "assessment owner and counselor read" on public.career_assessments for select to authenticated using (user_id = auth.uid() or public.current_role() in ('admin','counselor'));
create policy "assessment owner insert" on public.career_assessments for insert to authenticated with check (user_id = auth.uid());
create policy "assessment admin manage" on public.career_assessments for all to authenticated using (public.current_role() = 'admin') with check (public.current_role() = 'admin');

create policy "plans owner and staff read" on public.career_plans for select to authenticated using (user_id = auth.uid() or public.current_role() in ('admin','counselor'));
create policy "plans owner insert" on public.career_plans for insert to authenticated with check (user_id = auth.uid());
create policy "plans owner update" on public.career_plans for update to authenticated using (user_id = auth.uid()) with check (user_id = auth.uid());
create policy "plans admin manage" on public.career_plans for all to authenticated using (public.current_role() = 'admin') with check (public.current_role() = 'admin');

create policy "consult student and assigned staff read" on public.consultation_requests for select to authenticated using (student_id = auth.uid() or counselor_id = auth.uid() or public.current_role() in ('admin','counselor'));
create policy "consult student create" on public.consultation_requests for insert to authenticated with check (student_id = auth.uid());
create policy "consult staff update" on public.consultation_requests for update to authenticated using (public.current_role() in ('admin','counselor')) with check (public.current_role() in ('admin','counselor'));

create policy "published resources public read" on public.career_resources for select to anon, authenticated using (published = true or public.current_role() in ('admin','counselor'));
-- Admin dapat mengelola seluruh materi. Guru BK hanya dapat membuat dan mengelola materi miliknya sendiri.
create policy "admin manage all resources" on public.career_resources for all to authenticated using (public.current_role() = 'admin') with check (public.current_role() = 'admin');
create policy "counselor insert own resources" on public.career_resources for insert to authenticated with check (public.current_role() = 'counselor' and created_by = auth.uid());
create policy "counselor update own resources" on public.career_resources for update to authenticated using (public.current_role() = 'counselor' and created_by = auth.uid()) with check (public.current_role() = 'counselor' and created_by = auth.uid());
create policy "counselor delete own resources" on public.career_resources for delete to authenticated using (public.current_role() = 'counselor' and created_by = auth.uid());
create policy "career fields public read" on public.career_fields for select to anon, authenticated using (true);
create policy "staff manage career fields" on public.career_fields for all to authenticated using (public.current_role() in ('admin','counselor')) with check (public.current_role() in ('admin','counselor'));

grant usage on schema public to anon, authenticated;
grant select on public.career_fields to anon, authenticated;
grant select, insert, update on public.profiles to authenticated;
grant select, insert on public.career_assessments to authenticated;
grant select, insert, update on public.career_plans to authenticated;
grant select, insert, update on public.consultation_requests to authenticated;
grant select, insert, update, delete on public.career_resources to authenticated;
grant insert, select, update, delete on public.career_fields to authenticated;

-- Indeks untuk mempercepat dashboard dan pemantauan.
create index if not exists idx_profiles_role on public.profiles(role);
create index if not exists idx_assessments_user_created on public.career_assessments(user_id, created_at desc);
create index if not exists idx_plans_user_created on public.career_plans(user_id, created_at desc);
create index if not exists idx_consult_student_created on public.consultation_requests(student_id, created_at desc);
create index if not exists idx_consult_counselor_status on public.consultation_requests(counselor_id, status);
create index if not exists idx_resources_published_created on public.career_resources(published, created_at desc);
